"""Database management (works for SQLite and PostgreSQL).

    python manage.py init-db        create/upgrade tables (also runs automatically at app start)
    python manage.py seed           create demo account + synthetic data (demo@studyai.local / Demo@12345)
    python manage.py status         show database type, schema version and row counts
    python manage.py export-schema  write database/schema.sql (PostgreSQL) and database/schema.sqlite.sql
"""
import sys
from pathlib import Path

from dotenv import load_dotenv

load_dotenv()
import db  # noqa: E402


def main(cmd):
    if cmd == "init-db":
        print("schema version:", db.migrate())
    elif cmd == "seed":
        import seed
        db.migrate()
        with db.connection():
            seed.seed()
        print(f"Demo account ready: {seed.DEMO_EMAIL} / {seed.DEMO_PASSWORD}")
    elif cmd == "status":
        v = db.migrate()
        with db.connection() as c:
            print("database:", "postgres" if c.pg else "sqlite (" + db.sqlite_path() + ")", "| schema v", v)
            for t in ("users", "documents", "chunks", "notes", "quizzes", "flashcards", "study_plans", "activity_logs"):
                print(f"  {t:15}", c.one(f"SELECT COUNT(*) AS n FROM {t}")["n"])
    elif cmd == "export-schema":
        d = Path(__file__).parent / "database"
        d.mkdir(exist_ok=True)
        (d / "schema.sql").write_text("-- PostgreSQL schema (generated by `python manage.py export-schema`)\n\n" + db.schema_sql(True), encoding="utf-8")
        (d / "schema.sqlite.sql").write_text("-- SQLite schema (generated)\n\n" + db.schema_sql(False), encoding="utf-8")
        print("wrote database/schema.sql and database/schema.sqlite.sql")
    else:
        print(__doc__)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else ""))
